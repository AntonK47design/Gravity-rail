import type { LevelDef } from '../core/level';

const ring = (cx: number, cz: number): [number, number][] => {
  const out: [number, number][] = [];
  for (let x = cx - 1; x <= cx + 1; x++) for (let z = cz - 1; z <= cz + 1; z++) if (x !== cx || z !== cz) out.push([x, z]);
  return out;
};

